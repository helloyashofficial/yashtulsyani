#!/usr/bin/env python3
"""
gen-paste-manifest.py :: writes PASTE-MANIFEST.md from the blocks themselves.

Ported from FSDM. It lists every file in production-blocks and nothing else,
and refuses to run if a file has no known destination in ytconf.py, so the
manifest cannot drift from the folder the way FSDM's hand-written one did.
"""
import pathlib, re, sys
import ytconf as C

ORDER = {"/": 1, "/about": 2, "/work": 3, "/writing": 4, "/books": 5,
         "/reading": 6, "/notes": 7, "/now": 8, "/contact": 9}


def dest(p):
    n = p.name
    s = p.read_text(encoding="utf-8")
    if n == "01-sidebar.html":
        return ("1 Global", 0, "every page and every essay",
                "Paste FIRST, as its own Custom HTML block. It is the stylesheet: tokens, page globals, all essay CSS and the widget runtime.")
    if n in C.PAGES:
        url = C.PAGES[n]
        note = ""
        if url.startswith("/books/"):
            note = "Publish both book pages before re-pasting /books: the index links to them."
        if "provisional" in n:
            note = "Provisional. Replace wholesale when it has entries; do not grow it by hand."
        return ("2 Page", ORDER.get(url, 5.5), url, note)
    if re.match(r"\d\d-post-", n):
        slug = re.search(r"SLUG\s*:\s*(\S+)", s)
        if not slug:
            sys.exit("%s has no SLUG line in its header comment" % n)
        return ("3 Essay", 0, slug.group(1),
                "A WordPress Post, not a Page. Then re-paste /writing (card + schema).")
    if n in C.PRIVATE:
        return ("4 Private", 0, C.PRIVATE[n],
                "Set the page to Private or password protected AND noindex. noindex alone leaves it readable to anyone with the URL.")
    sys.exit("no known destination for %s; add it to ytconf.PAGES or PRIVATE" % n)


rows = sorted((dest(p) + (p.name,) for p in C.BLOCKS.glob("*.html")),
              key=lambda r: (r[0], r[1], r[2]))
out = ["# Paste manifest, yashtulsyani.com", "",
       "Generated by `generators/gen-paste-manifest.py` from the %d files in `production-blocks/`. "
       "Do not edit by hand: rerun `generators/build.sh`." % len(rows), "",
       "Order matters. The sidebar first, because every block inherits its tokens and every essay "
       "its CSS. Create a page before deleting whatever the navigation used to point at.", ""]
current = None
for group, _, url, note, name in rows:
    if group != current:
        current = group
        out += ["", "## " + group.split(" ", 1)[1], "", "| File | WordPress URL | Note |", "|---|---|---|"]
    out.append("| `%s` | `%s` | %s |" % (name, url, note))
(C.ROOT / "PASTE-MANIFEST.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("PASTE-MANIFEST.md: %d blocks" % len(rows))
